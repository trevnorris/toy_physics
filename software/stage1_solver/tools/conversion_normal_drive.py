"""Planar reversible material variation and a separate order-kinematics check.

The virtual displacement transports the constituent density and holds each
parcel's order fraction fixed. Shear, core energies and reservoirs are absent.
The example conversion law is imposed solely to test what the balance selects.
"""

import sympy as sp
from sympy.calculus.euler import euler_equations


def main():
    w, t, eps = sp.symbols("w t epsilon", real=True)
    n, chi, shift = [sp.Function(name)(w) for name in ("n", "chi", "shift")]
    a, kappa, eos, length, rate, n0 = sp.symbols("a k K ell lam n0", positive=True)
    u, front_speed = sp.symbols("u V", real=True)

    def well(c):
        return a*c**2*(1 - c)**2

    # Eulerian variations generated by a compactly supported displacement.
    nv = n - eps*sp.diff(n*shift, w)
    cv = chi - eps*shift*sp.diff(chi, w)
    energy = eos*nv**5/4 + well(cv) + kappa*sp.diff(cv, w)**2/2
    variation = sp.diff(energy, eps).subs(eps, 0)
    normal_force = -euler_equations(variation, shift, w)[0].lhs
    pressure_flux = eos*n**5 - well(chi) + kappa*sp.diff(chi, w)**2/2
    divergence_residual = sp.simplify(normal_force + sp.diff(pressure_flux, w))
    print("force plus derivative of compressive normal momentum flux =", divergence_residual)

    q = sp.symbols("q")
    bare_flux = -well(q) + kappa*(q*(1-q)/length)**2/2
    equilibrium_flux = sp.factor(bare_flux.subs(kappa, 2*a*length**2))
    flat_end_jump = sp.simplify(well(1) - well(0))
    print("bare order [flat-end flux jump, kink flux at arbitrary q] =",
          [flat_end_jump, equilibrium_flux])

    # Decreasing ordered-to-disordered profile. Both motions have the same
    # profile initially and the same conversion law wherever the front lies.
    exponential = sp.exp((w - front_speed*t)/length)
    profile = 1/(1 + exponential)
    gamma = -rate*profile*(1-profile)
    balance = sp.diff(n0*profile, t) + sp.diff(n0*profile*u, w) - n0*gamma
    slip = sp.solve(balance, u)[0] - front_speed
    slip = sp.simplify(slip)
    moving_front = sp.solve(sp.Eq(front_speed + slip, 0), front_speed)[0]
    currents = [n0*slip, sp.simplify(n0*(moving_front + slip))]
    print("u - V =", slip)
    print("fixed-cut number currents [stationary front, stationary material] =", currents)
    if divergence_residual != 0 or equilibrium_flux != 0 or flat_end_jump != 0:
        raise ValueError("Planar material variation or endpoint check failed")
    if sp.simplify(balance.subs(u, front_speed + slip)) != 0:
        raise ValueError("Relative velocity does not satisfy order conservation")


if __name__ == "__main__":
    main()
